def resign_app(install):
    """v1.0.9：改完 .app 内部文件后，对 WorkBuddy.app 重打 ad-hoc 签名。

    为什么必须做：WorkBuddy.app 原本带开发者签名，我们在
    Contents/Resources/app.asar.unpacked/ 里面改了 templates / product.json /
    codebuddy*.js 等文件，签名即告失效；Gatekeeper 下"签名失配的 app"
    会被判定为损坏 —— 表现就是群里反馈的
    「Mac 破甲完之后 WorkBuddy 打不开 / 提示已损坏，无法打开」。

    处理：codesign --force --deep --sign - 对整个 .app 重打 ad-hoc 签名。
    ad-hoc 签名不需要任何开发者证书，任何 Mac 都能做，Gatekeeper 即可放行。
    --revert 还原的是原始文件（内容与原签名重新对上），不需要本步。

    install = app.asar.unpacked 目录；.app 根从它向上回溯（正常三级）。
    """
    if not install or DRY_RUN:
        return
    app = None
    cur = install
    for _ in range(6):
        cur = os.path.dirname(cur)
        if cur.endswith(".app"):
            app = cur
            break
    if not app or not os.path.isdir(app):
        print("  [!] 未定位到 .app 根目录，跳过重签名。")
        return
    try:
        r = subprocess.run(
            ["codesign", "--force", "--deep", "--sign", "-", app],
            capture_output=True, text=True, timeout=180)
        if r.returncode == 0:
            print("  [+] 已重签名（ad-hoc）：%s" % app)
            return
        err = (r.stderr or r.stdout or "").strip()
        print("  [!] 重签名失败（注入本身不受影响，但 app 可能打不开）：%s" % err)
    except FileNotFoundError:
        print("  [!] 找不到 codesign 命令（非 macOS？）")
    except Exception as e:
        print("  [!] 重签名异常：%r" % (e,))
    # 兜底：把手动命令原样给出（含清隔离属性，防下载来源带 quarantine）
    print("      手动执行：")
    print("        codesign --force --deep --sign - '%s'" % app)
    print("        xattr -cr '%s'" % app)


def patch_tpl(path, persona_block):
    txt = read_text(path)
    if txt is None:
        return "skip"
    if _is_injected(txt):
        return "current"
    i = txt.find("<content_policy>")
    j = txt.find("</content_policy>", i)
    if i < 0 or j <= i:
        return "no-content-policy"
    backup(path)
    new = (txt[:i] + "<content_policy>\n" + persona_block + "\n</content_policy>"
           + txt[j + len("</content_policy>"):])
    write_text(path, new)
    return "patched"


def patch_json_prompt(path, persona_block):
    txt = read_text(path)
    if txt is None:
        return "skip"
    if _is_injected(txt):
        return "current"
    pb = persona_block.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    changed = False
    out = []
    pos = 0
    policy_count = txt.count("<content_policy>")
    while True:
        start = txt.find("<content_policy>", pos)
        if start < 0:
            break
        end = txt.find("</content_policy>", start)
        if end < 0:
            break
        out.extend((txt[pos:start], "<content_policy>\\n", pb, "\\n</content_policy>"))
        pos = end + len("</content_policy>")
        changed = True
    if changed:
        out.append(txt[pos:])
        target = backup(path)
        body = "".join(out)
        if target != path + BAK:
            write_text(target, body)
            return "patched-external(%s)" % os.path.basename(target)
        write_text(path, body)
        return "patched(content_policy x%d)" % policy_count
    backup(path)
    pat = re.compile(r'("(?:systemPrompt|system_prompt|basePrompt|prompt)"\s*:\s*")((?:[^"\\]|\\.)*)(")')
    n = 0

    def rep(m):
        nonlocal n
        if len(m.group(2)) > 200:
            n += 1
            return m.group(1) + pb + m.group(3)
        return m.group(0)

    new = pat.sub(rep, txt)
    if n == 0:
        new = re.sub(r"\{",
                     '{\n  "__pojia_persona": ' + json.dumps(persona_block, ensure_ascii=False) + ",",
                     txt, count=1)
    write_text(path, new)
    return "patched(%d fields)" % n


def patch_js(path):
    """命令闸门 / 网页内容过滤解锁（保守：只改常见拦截函数名）。"""
    txt = read_text(path)
    if txt is None:
        return "skip"
    orig = txt
    txt = txt.replace("confirmDangerousCommand", "confirmDangerousCommandDisabled")
    txt = re.sub(r"isCommandDenied\s*\(", "__pj_denied_never(", txt)
    txt = txt.replace("filterWebContent(", "__pj_webfilter_disabled(")
    if txt != orig:
        backup(path)
        write_text(path, txt)
        return "patched"
    return "current-or-n/a"


