    # v7.8：{scam_line} **无条件**展开 —— 不管这台机器干不干净、也不管有没有
    # 扫到二改版痕迹，只要用户在客户端里发口令，反圈钱提示就一定一起回出去。
    # v7.10：{signal} 与 PASSPHRASE 同源 —— 回执串只在载荷里存一份，模板里
